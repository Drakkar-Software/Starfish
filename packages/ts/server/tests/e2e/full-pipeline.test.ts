/**
 * End-to-end pipeline test for the Starfish v3 stack.
 *
 * Wires the full chain through an in-memory Hono transport:
 *
 *   bootstrapRootIdentity  (alice — passphrase → root + self-signed device cap)
 *   ↓
 *   StarfishClient(capProvider)  (signs every request with cap + Ed25519 sig)
 *   ↓
 *   SyncRouter + createCapCertRoleResolver  (verifies cap, request sig, nonce)
 *   ↓
 *   createKeyringEncryptor  (HPKE-DHKEM wrap → AES-GCM)
 *   ↓
 *   round-trip: push encrypted → pull encrypted → decrypt
 *   ↓
 *   pair bob via mintDeviceCap + addRecipient → bob pushes → alice pulls
 *
 * Goal: lock the integration. Per-layer correctness lives in the unit tests.
 */

